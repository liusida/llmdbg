class ExtensionManifestTest(unittest.TestCase):
    def test_debugger_activation_and_contribution_match(self) -> None:
        root = Path(__file__).resolve().parents[1]
        manifest = json.loads((root / "vscode-extension" / "package.json").read_text())

        self.assertIn("onDebug", manifest["activationEvents"])
        debugger_types = {debugger["type"] for debugger in manifest["contributes"]["debuggers"]}
        self.assertIn("llmdbg", debugger_types)
        self.assertEqual(manifest["main"], "./extension.js")
        self.assertEqual(manifest["icon"], "assets/icon.png")
        self.assertTrue((root / "vscode-extension" / manifest["icon"]).is_file())
        self.assertIn("bundled/**", manifest["files"])
        self.assertIn("assets/**", manifest["files"])
        self.assertIn("stage-adapter", manifest["scripts"])
        self.assertEqual(manifest["contributes"]["languages"][0]["extensions"], [".llmdbg"])
        self.assertEqual(manifest["contributes"]["languages"][1]["extensions"], [".llmdbg.py"])
        language_configuration = manifest["contributes"]["languages"][1]["configuration"]
        configuration_path = root / "vscode-extension" / language_configuration
        self.assertTrue(configuration_path.is_file())
        configuration = json.loads(configuration_path.read_text())
        self.assertEqual(configuration["comments"]["lineComment"], "#")
        self.assertEqual(manifest["contributes"]["breakpoints"][0]["language"], "llmdbg")
        self.assertEqual(manifest["contributes"]["breakpoints"][1]["language"], "llmdbg-python")
        command_ids = {command["command"] for command in manifest["contributes"]["commands"]}
        self.assertIn("llmdbg.initializeProject", command_ids)
        self.assertIn("llmdbg.showRuntimeDiagnostics", command_ids)
        self.assertIn("llmdbg.rebuildRuntime", command_ids)
        self.assertIn("llmdbg.plotCurrentVector", command_ids)
        self.assertIn("llmdbg.showNeuronLens", command_ids)
        self.assertIn("llmdbg.showPromptTokens", command_ids)
        self.assertIn("llmdbg.unloadModel", command_ids)
        self.assertIn("llmdbg.showModelStatus", command_ids)
        self.assertIn("llmdbg.manageResidualToVocabularyLenses", command_ids)
        configuration_sections = manifest["contributes"]["configuration"]
        self.assertEqual(
            [section["title"] for section in configuration_sections],
            ["llmdbg: General", "llmdbg: Lens URLs", "llmdbg: Interface"],
        )
        settings = {
            key: value
            for section in configuration_sections
            for key, value in section["properties"].items()
        }
        self.assertIn("llmdbg.jLensSource", settings)
        self.assertIn("llmdbg.rLensSource", settings)
        self.assertIn("llmdbg.jppLensSource", settings)
        source = (root / "vscode-extension" / "extension.js").read_text()
        self.assertIn('method: "jpp", source: jppSource, indexSection: "workspace_lenses"', source)
        self.assertNotIn("llmdbg.residualToVocabularyLenses", settings)
        custom = settings["llmdbg.customResidualToVocabularyLenses"]
        self.assertEqual(custom["default"][0]["label"], "Official J++ Lens")
        self.assertEqual(custom["default"][1]["label"], "Neuronpedia J Lens")
        self.assertNotIn("models", custom["default"][1])
        self.assertNotIn("revision", custom["default"][1])
        self.assertEqual(custom["default"][2]["label"], "Neuronpedia J++ Lens")
        commands = {
            command["command"]: command for command in manifest["contributes"]["commands"]
        }
        self.assertEqual(commands["llmdbg.showNeuronLens"]["icon"]["dark"], "assets/lens-dark.svg")
        self.assertEqual(commands["llmdbg.plotCurrentVector"]["icon"]["dark"], "assets/plot-dark.svg")
        toolbar = manifest["contributes"]["menus"]["debug/toolBar"]
        self.assertEqual(
            [(item["command"], item["group"]) for item in toolbar],
            [
                ("llmdbg.showNeuronLens", "llmdbg@1"),
                ("llmdbg.plotCurrentVector", "llmdbg@2"),
                ("llmdbg.showPromptTokens", "llmdbg@3"),
            ],
        )

